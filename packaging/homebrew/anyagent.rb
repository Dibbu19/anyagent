# Homebrew formula template. Put it in a tap repo (github.com/<you>/homebrew-anyagent/Formula/anyagent.rb),
# then: brew tap <you>/anyagent && brew install anyagent
# Fill in url/sha256 from the PyPI sdist of the release and run `brew update-python-resources anyagent`
# to generate the resource blocks for ollama, rich, prompt_toolkit and their dependencies.
class Anyagent < Formula
  include Language::Python::Virtualenv

  desc "Local coding agent (Ollama, OpenAI-compatible, Anthropic) with a Claude Code-style terminal UI"
  homepage "https://github.com/<you>/anyagent"
  url "https://files.pythonhosted.org/packages/source/a/anyagent/anyagent-0.3.0.tar.gz"
  sha256 "REPLACE_WITH_SDIST_SHA256"
  license "MIT"

  depends_on "python@3.12"

  # resource "ollama" do ... end   # generated by `brew update-python-resources anyagent`

  def install
    virtualenv_install_with_resources
  end

  test do
    assert_match "anyagent", shell_output("#{bin}/any --version")
  end
end
